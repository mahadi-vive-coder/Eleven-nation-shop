-- ------------------------------------------------------------------------------
-- 14. ATOMIC ORDER CREATION & INVENTORY DEDUCTION (Row Locking RPC)
-- ------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.create_order_atomic(
  order_payload JSONB,
  items_payload JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $
DECLARE
  v_order_id UUID;
  v_order_number TEXT;
  v_item JSONB;
  v_product_id UUID;
  v_requested_qty INTEGER;
  v_requested_size TEXT;
  v_curr_stock INTEGER;
  v_curr_sizes JSONB;
  v_new_sizes JSONB;
  v_size_found BOOLEAN;
  v_size_elem JSONB;
  v_avail_size_stock INTEGER;
  v_new_size_stock INTEGER;
  v_product_name TEXT;
  v_product_selling_price NUMERIC;
  v_product_cost_price NUMERIC;
BEGIN
  -- 1. Basic validation
  IF items_payload IS NULL OR jsonb_array_length(items_payload) = 0 THEN
    RAISE EXCEPTION 'Order creation failed: at least one order item is required.';
  END IF;

  v_order_number := order_payload->>'order_number';
  IF v_order_number IS NULL OR trim(v_order_number) = '' THEN
    RAISE EXCEPTION 'Order number is required';
  END IF;

  -- 2. Lock each product row FOR UPDATE and validate stock
  FOR v_item IN SELECT * FROM jsonb_array_elements(items_payload) LOOP
    v_product_id := (v_item->>'product_id')::UUID;
    v_requested_size := v_item->>'size';
    v_requested_qty := (v_item->>'quantity')::INTEGER;

    IF v_requested_qty <= 0 THEN
      RAISE EXCEPTION 'Invalid item quantity: %', v_requested_qty;
    END IF;

    -- Row-level locking on products table
    SELECT name, stock, sizes, selling_price, cost_price
    INTO v_product_name, v_curr_stock, v_curr_sizes, v_product_selling_price, v_product_cost_price
    FROM public.products
    WHERE id = v_product_id AND status = 'active'
    FOR UPDATE;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Product % is not found or inactive', v_product_id;
    END IF;

    IF v_curr_stock < v_requested_qty THEN
      RAISE EXCEPTION 'Insufficient inventory for %: requested %, but only % in stock',
        v_product_name, v_requested_qty, v_curr_stock;
    END IF;

    -- Validate and deduct specific size variant
    v_size_found := false;
    v_new_sizes := '[]'::jsonb;

    FOR v_size_elem IN SELECT * FROM jsonb_array_elements(v_curr_sizes) LOOP
      IF lower(v_size_elem->>'size') = lower(v_requested_size) THEN
        v_size_found := true;
        v_avail_size_stock := (v_size_elem->>'stock')::INTEGER;

        IF v_avail_size_stock < v_requested_qty THEN
          RAISE EXCEPTION 'Insufficient stock for % (Size %): requested %, available %',
            v_product_name, v_requested_size, v_requested_qty, v_avail_size_stock;
        END IF;

        v_new_size_stock := v_avail_size_stock - v_requested_qty;
        v_new_sizes := v_new_sizes || jsonb_build_object('size', v_size_elem->>'size', 'stock', v_new_size_stock);
      ELSE
        v_new_sizes := v_new_sizes || v_size_elem;
      END IF;
    END LOOP;

    IF NOT v_size_found THEN
      RAISE EXCEPTION 'Size % not found for product %', v_requested_size, v_product_name;
    END IF;

    -- Update inventory atomically
    UPDATE public.products
    SET
      sizes = v_new_sizes,
      stock = stock - v_requested_qty,
      updated_at = NOW()
    WHERE id = v_product_id;
  END LOOP;

  -- 3. Insert Order
  INSERT INTO public.orders (
    order_number,
    customer_id,
    customer_name,
    customer_email,
    customer_phone,
    shipping_address,
    city,
    postal_code,
    items_count,
    subtotal,
    customization_total,
    delivery_fee,
    discount,
    total_amount,
    total_cost,
    gross_profit,
    profit_margin_percent,
    payment_method,
    payment_status,
    order_status,
    courier_name,
    tracking_number,
    admin_notes,
    customer_notes,
    is_custom_order
  ) VALUES (
    v_order_number,
    NULLIF(order_payload->>'customer_id', '')::UUID,
    order_payload->>'customer_name',
    order_payload->>'customer_email',
    order_payload->>'customer_phone',
    order_payload->>'shipping_address',
    COALESCE(order_payload->>'city', 'Dhaka'),
    order_payload->>'postal_code',
    (order_payload->>'items_count')::INTEGER,
    (order_payload->>'subtotal')::NUMERIC,
    COALESCE((order_payload->>'customization_total')::NUMERIC, 0),
    COALESCE((order_payload->>'delivery_fee')::NUMERIC, 0),
    COALESCE((order_payload->>'discount')::NUMERIC, 0),
    (order_payload->>'total_amount')::NUMERIC,
    COALESCE((order_payload->>'total_cost')::NUMERIC, 0),
    COALESCE((order_payload->>'gross_profit')::NUMERIC, 0),
    COALESCE((order_payload->>'profit_margin_percent')::NUMERIC, 0),
    COALESCE(order_payload->>'payment_method', 'cod'),
    COALESCE(order_payload->>'payment_status', 'pending'),
    COALESCE(order_payload->>'order_status', 'pending'),
    order_payload->>'courier_name',
    order_payload->>'tracking_number',
    order_payload->>'admin_notes',
    order_payload->>'customer_notes',
    COALESCE((order_payload->>'is_custom_order')::BOOLEAN, false)
  )
  RETURNING id INTO v_order_id;

  -- 4. Insert Order Items
  FOR v_item IN SELECT * FROM jsonb_array_elements(items_payload) LOOP
    INSERT INTO public.order_items (
      order_id,
      product_id,
      product_name,
      product_sku,
      product_image,
      size,
      quantity,
      unit_price,
      cost_price,
      customization_fee,
      custom_name,
      custom_number,
      subtotal
    ) VALUES (
      v_order_id,
      (v_item->>'product_id')::UUID,
      v_item->>'product_name',
      v_item->>'product_sku',
      v_item->>'product_image',
      v_item->>'size',
      (v_item->>'quantity')::INTEGER,
      (v_item->>'unit_price')::NUMERIC,
      (v_item->>'cost_price')::NUMERIC,
      COALESCE((v_item->>'customization_fee')::NUMERIC, 0),
      v_item->>'player_name',
      v_item->>'player_number',
      (v_item->>'subtotal')::NUMERIC
    );
  END LOOP;

  RETURN jsonb_build_object(
    'success', true,
    'order_id', v_order_id,
    'order_number', v_order_number
  );
END;
$;

